'use client';
import type { AnalysisResult } from '@/lib/types';
import { OriginalPane } from './OriginalPane';
import { Breakdown } from './Breakdown';
import { Loading } from './Loading';
import { ResultsReader } from './ResultsReader';
import { Doc, Sparkle, Flag, Back, Copy, Download } from './icons';

interface Props {
  docText: string;
  result: AnalysisResult | null;
  loading: boolean;
  error: string;
  level: number;
  onChangeLevel: (l: number) => void;
  onBack: () => void;
  onRetry: () => void;
  toast: (msg: string) => void;
}

// Shared body sections for both copy and download — parameterized for quote spacing
function buildBodyLines(result: AnalysisResult, quoteSpacing: '  ' | ' ' = ' '): string[] {
  return [
    'IN A NUTSHELL', ...result.summary.map((s) => '• ' + s), '',
    'WHAT IT ASKS OF YOU', ...result.requires.map((s) => '• ' + s), '',
    'RED FLAGS TO WATCH',
    ...result.redFlags.map((f) => '• ' + f.flag + (f.quote ? `${quoteSpacing}("${f.quote}")` : '')), '',
    'COMMON MISTAKES PEOPLE MAKE', ...result.mistakes.map((s) => '• ' + s),
  ];
}

export function Results({ docText, result, loading, error, level, onChangeLevel, onBack, onRetry, toast }: Props) {
  const quotes = result ? result.redFlags.map((f) => f.quote).filter(Boolean) : [];

  const copyOutput = () => {
    if (!result) return;
    const lines = [
      `PLAIN-LANGUAGE BREAKDOWN — ${result.docLabel}`, '',
      'WHAT THIS DOCUMENT IS', result.docType, '',
      ...buildBodyLines(result, '  '), '',
      '— Generated by Plainly. This is information, not legal advice. Consult a licensed attorney before acting.',
    ];
    navigator.clipboard.writeText(lines.join('\n')).then(() => toast('Breakdown copied to clipboard'));
  };

  const download = () => {
    if (!result) return;
    const lines = [
      `Plain-Language Breakdown — ${result.docLabel}`, '='.repeat(40), '',
      result.docType, '',
      ...buildBodyLines(result, ' '), '',
      'This is information, not legal advice. Consult a licensed attorney before acting.',
    ];
    const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = 'plain-language-breakdown.txt'; a.click();
    URL.revokeObjectURL(url);
    toast('Saved as a text file');
  };

  return (
    <div className="results fade-up">
      <div className="wrap">
        <div className="results-bar">
          <button className="btn btn-ghost btn-sm" onClick={onBack}><Back s={15} /> New document</button>
          <h2>Plain-language breakdown</h2>
          {result && <span className="doc-pill"><Doc s={14} c="#5f4a78" /> {result.docLabel}</span>}
          <div className="spacer" />
          {result && (
            <div className="action-row">
              <button className="btn btn-ghost btn-sm" onClick={copyOutput}><Copy s={15} /> Copy</button>
              <button className="btn btn-ghost btn-sm" onClick={download}><Download s={15} /> Save</button>
            </div>
          )}
        </div>

        {(result || loading) && !error && (
          <ResultsReader level={level} busy={loading} onApply={onChangeLevel} />
        )}

        <div className="split">
          <OriginalPane text={docText} quotes={quotes} />
          <div>
            {error ? (
              <div className="breakdown">
                <div className="error-box"><Flag s={16} c="#bb5230" /> {error}</div>
                <button className="btn btn-primary" style={{ marginTop: 16, alignSelf: 'flex-start' }} onClick={onRetry}><Sparkle s={16} c="#fff" /> Try again</button>
              </div>
            ) : loading || !result ? (
              <Loading />
            ) : (
              <Breakdown result={result} />
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
